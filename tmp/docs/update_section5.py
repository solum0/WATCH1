def delete_paragraph(paragraph):
    element = paragraph._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)
    paragraph._p = paragraph._element = None


def find_targets(document):
    paragraphs = list(document.paragraphs)
    i_51 = None
    i_52 = None
    i_ref_item = None

    for index, paragraph in enumerate(paragraphs):
        text = paragraph.text.strip()
        if text.startswith("5.1 "):
            i_51 = index
        elif text.startswith("5.2 ") and text.count(".") == 1:
            i_52 = index
        elif text.startswith("[1]"):
            i_ref_item = index
            break

    if i_ref_item is None:
        raise RuntimeError("Failed to locate the first reference entry.")

    i_ref = None
    for index in range(i_ref_item - 1, -1, -1):
        if paragraphs[index].text.strip():
            i_ref = index
            break

    if i_51 is None or i_52 is None or i_ref is None:
        raise RuntimeError("Failed to locate the target headings in the document.")

    return paragraphs, i_51, i_52, i_ref


def main():
    document = Document(DOC_PATH)
    paragraphs, i_51, i_52, i_ref = find_targets(document)
    p_52 = paragraphs[i_52]
    p_ref = paragraphs[i_ref]

    for paragraph in paragraphs[i_51 + 1:i_52]:
        delete_paragraph(paragraph)

    for paragraph in paragraphs[i_52 + 1:i_ref]:
        delete_paragraph(paragraph)

    for text in SECTION_51:
        p_52.insert_paragraph_before(text, style="本科论文正文")

    for kind, text in SECTION_52:
        style = "Heading 3" if kind == "h3" else "本科论文正文"
        p_ref.insert_paragraph_before(text, style=style)

    document.save(DOC_PATH)
    print(f"Updated: {DOC_PATH}")


if __name__ == "__main__":
    main()
